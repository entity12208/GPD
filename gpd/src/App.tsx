type Route =
  | 'menu' | 'auth' | 'play' | 'game' | 'settings' | 'stats' | 'leaderboard'
  | 'friends' | 'notifications' | 'mygames' | 'rules' | 'online' | 'resume' | 'lobby';

/** The seat this client holds in an online game that has already started. */
interface GameSeat {
  gameId: string;
  userId: string;
  meSeat: number;
  isHost: boolean;
  channel: online.NetChannel;
}

/** Everything about the online game this client is currently attached to. */
/** The desktop client shipped alongside the web build (generated by tools/build-desktop-zip.mjs). */
const DESKTOP_DOWNLOAD = `${import.meta.env.BASE_URL ?? '/'}gpd-desktop.zip`;
const DESKTOP_SIZE = '≈100 KB';

interface OnlineSlot {
  gameId: string;
  userId: string;
  username: string;
  isHost: boolean;
  /** My row in `game_players`. */
  seat: number;
  capacity: number;
  cfg: GameConfig;
  channel: online.NetChannel;
  seats: online.SeatRow[];
  status: online.LobbyRow['status'];
}

const JOIN_PROBLEM: Record<string, string> = {
  'wrong-password': 'Wrong room password.',
  'invite-only': 'That game is private — ask the host to invite your username.',
  full: 'That game is already full.',
  closed: 'That game is no longer open.',
  unknown: 'Could not join the game.',
};

export default function App() {
  const [settings, setSettings] = useState<Settings>(() => loadSettings());
  const [profile, setProfile] = useState<LocalProfile | null>(() => loadProfile());
  const [games, setGames] = useState<GameResult[]>(() => loadGames());
  const [saved, setSaved] = useState<SavedGameMeta[]>(() => listSavedGames());
  const [sessions, setSessions] = useState<OnlineSession[]>(() => listOnlineSessions());
  const [route, setRoute] = useState<Route>('menu');
  const [runner, setRunner] = useState<GameRunner | null>(null);
  const [session, setSession] = useState<GameSeat | null>(null);
  const [slot, setSlot] = useState<OnlineSlot | null>(null);
  const [toast, setToast] = useState<string | null>(null);
  const lastConfig = useRef<{ cfg: GameConfig; names: string[] } | null>(null);

  const runnerRef = useRef<GameRunner | null>(null);
  const slotRef = useRef<OnlineSlot | null>(null);
  const broadcastRef = useRef<(() => void) | null>(null);
  const lastTurn = useRef<number | null>(null);
  const pushTimer = useRef<number | null>(null);

  useEffect(() => { saveSettings(settings); updateSfx(settings); }, [settings]);
  useEffect(() => { initSfx(settings); }, [settings]);
  useEffect(() => { saveProfile(profile); }, [profile]);
  useEffect(() => { runnerRef.current = runner; }, [runner]);

  const notify = useCallback((m: string) => {
    setToast(m);
    window.setTimeout(() => setToast((t) => (t === m ? null : t)), 3600);
  }, []);

  /** Turn reminders are best-effort: an in-app toast plus a desktop notification. */
  const alertTurn = useCallback((name: string) => {
    notify(`Your turn${name ? ` — moving for ${name}` : ''}!`);
    sfx('turn');
    try {
      if (typeof Notification !== 'undefined' && Notification.permission === 'granted') {
        new Notification('GPD — it is your turn', { body: 'Your move is waiting in an online game.' });
      }
    } catch { /* notifications are optional */ }
  }, [notify]);

  const askNotificationPermission = useCallback(() => {
    try {
      if (typeof Notification !== 'undefined' && Notification.permission === 'default') void Notification.requestPermission();
    } catch { /* ignore */ }
  }, []);

  const finish = useCallback((r: GameResult) => {
    setGames(recordGame(r, profile?.username ?? null));
    if (profile?.remoteId && session) {
      void online.recordScoreEvents(session.gameId, profile.remoteId, r.scoreEvents.map((e) => e.key));
      deleteOnlineSession(session.gameId);
      setSessions(listOnlineSessions());
    }
    sfx(r.winner !== null && r.standings[r.winner]?.name === profile?.username ? 'win' : 'lose');
  }, [profile, session]);

  /** Launch an offline game. */
  const startOffline = useCallback((cfg: GameConfig, names: string[]) => {
    lastConfig.current = { cfg, names };
    const game = new GPDGame(cfg, names);
    const sim = cfg.mode === 'offline-sim';
    const r = new GameRunner(game, {
      speed: sim ? 20 : cfg.mode === 'offline-multi' ? 0 : 700,
      tickMs: sim ? 40 : settings.fps === 30 ? 66 : 33,
      stepsPerTick: sim ? 60 : 1,
    });
    r.autoBots = true;
    setSession(null);
    setRunner(r);
    setRoute('game');
    r.start();
  }, [settings.fps]);

  // -------------------------------------------------------------- online play
  /**
   * Attach this client to an online game: open the shared channel, take the real
   * roster and drop into the lobby (or straight back onto the board if the game is
   * already running).
   */
  const enterOnline = useCallback(async (row: online.LobbyRow, cfg: GameConfig, uid: string, username: string) => {
    const isHost = row.host_id === uid;
    const gameId = row.id;
    let channel: online.NetChannel;
    lastTurn.current = null;

    /** Host: everyone gets the newest snapshot and the new actor is told it is their turn. */
    const broadcast = () => {
      const g = runnerRef.current?.game;
      const cur = slotRef.current;
      if (!g || !cur) return;
      const status = g.state.phase === 'finished' ? 'finished'
        : g.state.phase === 'placement' ? 'placement' : 'active';
      channel.sendState(g.state, status);
      if (pushTimer.current) window.clearTimeout(pushTimer.current);
      pushTimer.current = window.setTimeout(() => {
        void online.pushState(cur.gameId, g.state, status, null, g.rng.state);
      }, 400);
      const a = g.actor;
      if (a && status !== 'finished' && lastTurn.current !== a.id) {
        lastTurn.current = a.id;
        channel.sendTurn({ seat: a.id, name: a.name, team: a.team });
        // In Tournament mode the whole team may move, so every teammate who can act
        // gets the reminder, not only the player whose seat is nominally up.
        const movers = g.eligibleActors();
        for (const m of movers) {
          const seatNo = cur.seats[m.id]?.seat;
          if (seatNo === undefined || seatNo === cur.seat) continue;
          void online.notifyTurn(cur.gameId, seatNo,
            g.state.config.tournament
              ? `It is your team's turn in round ${g.state.round}.`
              : `It is your turn in round ${g.state.round}.`);
        }
      }
    };

    /** Guest: adopt whatever the host sends. */
    const adopt = (state: GameState, status: string) => {
      const cur = slotRef.current;
      const existing = runnerRef.current;
      const idx = Math.max(0, (cur?.seats ?? []).findIndex((s) => s.userId === uid));
      if (existing) {
        existing.game = GPDGame.fromJSON(JSON.stringify(state));
        existing.kick();
      } else {
        const g = GPDGame.fromJSON(JSON.stringify(state));
        const r = new GameRunner(g, { speed: 700, tickMs: 60 });
        r.autoBots = false;
        // Only the host advances the clock; a guest renders what it is told.
        r.readOnly = true;
        r.remote = (p) => channel.sendAction(p);
        runnerRef.current = r;
        setRunner(r);
        setSession({ gameId, userId: uid, meSeat: idx, isHost: false, channel });
        r.start();
      }
      if (status !== 'lobby') {
        setSlot((s) => (s ? { ...s, status: status as OnlineSlot['status'] } : s));
        setRoute('game');
      }
    };

    channel = online.openGameChannel(gameId, uid, {
      onState: (state, status) => { if (!isHost) adopt(state, status); },
      onAction: (payload, from) => {
        if (!isHost) return;
        const g = runnerRef.current?.game;
        if (!g) return;
        const seat = Number(from);
        if (Number.isNaN(seat)) return;
        applyPayload(g, seat, payload as NetPayload);
        broadcast();
      },
      onHello: () => { if (isHost) broadcast(); },
      onStart: (snap) => {
        if (isHost) return;
        const g = new GPDGame(snap.config, snap.names);
        const r = new GameRunner(g, { speed: 700, tickMs: 60 });
        r.autoBots = false;
        r.readOnly = true;
        r.remote = (p) => channel.sendAction(p);
        runnerRef.current = r;
        const idx = Math.max(0, snap.seats.findIndex((s) => s.userId === uid));
        setRunner(r);
        setSession({ gameId, userId: uid, meSeat: idx, isHost: false, channel });
        setSlot((s) => (s ? { ...s, status: 'placement', seats: snap.seats, cfg: snap.config } : s));
        setRoute('game');
        r.start();
      },
      onTurn: (t) => {
        const cur = slotRef.current;
        if (!cur) return;
        const myIdx = cur.seats.findIndex((s) => s.userId === uid);
        if (myIdx < 0) return;
        // Tournament turns belong to a team, so any teammate is on the clock.
        const mine = cur.cfg.tournament
          ? teamFor(cur.cfg.preset ?? 'classic', myIdx, cur.seats.length) === t.team
          : myIdx === t.seat;
        if (mine) alertTurn(t.name);
      },
    });

    if (!(await channel.ready)) {
      channel.close();
      notify('Could not reach Supabase Realtime — enable it for this project and try again.');
      return;
    }
    broadcastRef.current = broadcast;

    const seats = await online.listSeats(gameId);
    const mySeat = seats.find((s) => s.userId === uid)?.seat ?? 0;
    const myIdx = Math.max(0, seats.findIndex((s) => s.userId === uid));
    const next: OnlineSlot = {
      gameId, userId: uid, username, isHost, seat: mySeat,
      capacity: row.capacity ?? 12, cfg, channel, seats, status: row.status,
    };
    slotRef.current = next;
    setSlot(next);
    saveOnlineSession({
      gameId, userId: uid, username, seat: mySeat, isHost,
      preset: cfg.preset ?? (cfg.tournament ? 'tournament' : 'classic'),
      mapPreset: cfg.mapPreset, mode: cfg.mode, status: row.status,
    });
    setSessions(listOnlineSessions());

    if (row.status === 'lobby') {
      setRoute('lobby');
      if (isHost) channel.sendLobby({ status: row.status, capacity: next.capacity, hostId: row.host_id ?? null, seats });
      return;
    }
    // The game is already under way. The host is authoritative and rebuilds from
    // the stored snapshot; a guest asks for the current board.
    if (isHost && row.state) {
      const g = GPDGame.fromJSON(JSON.stringify(row.state));
      if (row.rng) g.rng.state = Number(row.rng);
      const r = new GameRunner(g, { speed: 700, tickMs: 60 });
      r.autoBots = false;
      r.onEvent = () => broadcastRef.current?.();
      runnerRef.current = r;
      setRunner(r);
      setSession({ gameId, userId: uid, meSeat: myIdx, isHost: true, channel });
      setRoute('game');
      r.start();
      broadcast();
    } else {
      setRoute('lobby');
      channel.requestState();
    }
  }, [alertTurn, notify]);

  /** Host: create the lobby and wait for players (the game does not start yet). */
  const hostOnline = useCallback((cfg: GameConfig, _names: string[], lobbyOpts?: LobbyOptions) => {
    const uid = profile?.remoteId;
    if (!uid) { notify('Sign in to host an online game.'); return; }
    askNotificationPermission();
    void (async () => {
      try {
        const row = await online.createLobby(cfg, uid, lobbyOpts);
        await enterOnline(row, cfg, uid, profile!.username);
        notify(lobbyOpts?.visibility === 'private'
          ? 'Private lobby created — invitations were sent to the usernames you listed.'
          : 'Lobby created — players can find it under Open games.');
      } catch (e) {
        notify(errorMessage(e, 'Could not host the game'));
      }
    })();
  }, [profile, notify, enterOnline, askNotificationPermission]);

  /** Join an existing online game, then wait in its lobby. */
  const joinLobby = useCallback((lobbyId: string, password?: string) => {
    const uid = profile?.remoteId;
    if (!uid) { notify('Sign in to join an online game.'); return; }
    askNotificationPermission();
    void (async () => {
      try {
        const status = await online.joinGame(lobbyId, password);
        if (status !== 'ok') { notify(JOIN_PROBLEM[status] ?? 'Could not join the game.'); return; }
        const row = await online.fetchGame(lobbyId);
        if (!row) { notify('That game is no longer available.'); return; }
        await enterOnline(row, online.configFromLobby(row), uid, profile!.username);
      } catch (e) {
        notify(errorMessage(e, 'Could not join the game'));
      }
    })();
  }, [profile, notify, enterOnline, askNotificationPermission]);

  /** Host: close the lobby and start the game with the players who joined. */
  const startLobby = useCallback(() => {
    const cur = slotRef.current;
    if (!cur || !cur.isHost) return;
    void (async () => {
      const seats = await online.listSeats(cur.gameId);
      const cfg: GameConfig = { ...cur.cfg, humanPlayers: seats.length, playerCount: seats.length };
      const problem = configProblem(cfg);
      if (problem) { notify(problem); return; }
      if (seats.length < 2) { notify('At least two players are needed to start.'); return; }
      const names = seats.map((s) => s.username);
      const game = new GPDGame(cfg, names);
      const r = new GameRunner(game, { speed: 700, tickMs: 60 });
      r.autoBots = false;
      r.onEvent = () => broadcastRef.current?.();
      const myIdx = Math.max(0, seats.findIndex((s) => s.userId === cur.userId));
      const next: OnlineSlot = { ...cur, seats, status: 'placement', cfg };
      slotRef.current = next; setSlot(next);
      runnerRef.current = r;
      setRunner(r);
      setSession({ gameId: cur.gameId, userId: cur.userId, meSeat: myIdx, isHost: true, channel: cur.channel });
      setRoute('game');
      r.start();
      cur.channel.sendStart({ config: cfg, names, seats });
      broadcastRef.current?.();
      saveOnlineSession({
        gameId: cur.gameId, userId: cur.userId, username: cur.username, seat: cur.seat,
        isHost: true, preset: cfg.preset ?? 'classic', mapPreset: cfg.mapPreset,
        mode: cfg.mode, status: 'placement',
      });
      setSessions(listOnlineSessions());
    })();
  }, [notify]);

  /** Give up the seat (used when a lobby is abandoned before it starts). */
  const leaveLobby = useCallback(() => {
    const cur = slotRef.current;
    void (async () => {
      try {
        if (cur) {
          if (cur.isHost) await online.closeGame(cur.gameId);
          else await online.leaveSeat(cur.gameId, cur.userId);
          deleteOnlineSession(cur.gameId);
          setSessions(listOnlineSessions());
          cur.channel.close();
        }
      } catch { /* best effort */ }
      slotRef.current = null;
      broadcastRef.current = null;
      setSlot(null);
      setRoute('online');
      notify(cur?.isHost ? 'Lobby closed.' : 'You left the lobby.');
    })();
  }, [notify]);

  const closeSlot = () => {
    slotRef.current?.channel.close();
    slotRef.current = null;
    broadcastRef.current = null;
    setSlot(null);
  };

  /** Step away from a running game but keep the seat, so it can be rejoined. */
  const stepAway = useCallback(() => {
    runner?.stop();
    closeSlot();
    setRunner(null);
    setSession(null);
    setRoute('menu');
    notify('You stepped away. Your seat is kept — rejoin from Online multiplayer.');
  }, [runner, notify]);

  /** Quit for good: free the seat and remove the game from the rejoin list. */
  const forfeitGame = useCallback(() => {
    const cur = slotRef.current;
    void (async () => {
      try {
        if (cur) {
          if (cur.isHost) {
            const g = runnerRef.current?.game;
            if (g) { g.abandon(); broadcastRef.current?.(); }
            await online.closeGame(cur.gameId);
          } else {
            cur.channel.sendAction({ t: 'forfeit' });
            await online.leaveSeat(cur.gameId, cur.userId);
          }
          deleteOnlineSession(cur.gameId);
          setSessions(listOnlineSessions());
        }
      } catch { /* best effort */ }
      runner?.stop();
      closeSlot();
      setRunner(null);
      setSession(null);
      setRoute('menu');
      notify(cur?.isHost ? 'You closed the game.' : 'You forfeited the game.');
    })();
  }, [runner, notify]);

  /** Reopen an online game this account is already part of. */
  const resumeOnline = useCallback((s: OnlineSession) => {
    const uid = profile?.remoteId;
    if (!uid || uid !== s.userId) { notify('Sign in as the account that joined this game.'); return; }
    askNotificationPermission();
    void (async () => {
      try {
        const row = await online.fetchGame(s.gameId);
        if (!row || row.status === 'finished') {
          deleteOnlineSession(s.gameId); setSessions(listOnlineSessions());
          notify('That game has finished.');
          return;
        }
        const status = await online.joinGame(row.id, undefined, -1);
        if (status !== 'ok') { notify(JOIN_PROBLEM[status] ?? 'Could not rejoin the game.'); return; }
        await enterOnline(row, online.configFromLobby(row), uid, profile!.username);
      } catch (e) {
        notify(errorMessage(e, 'Could not rejoin the game'));
      }
    })();
  }, [profile, notify, enterOnline, askNotificationPermission]);

  const leaveGame = useCallback(() => {
    session?.channel.close();
    runner?.stop();
    setRunner(null);
    setSession(null);
    setRoute('menu');
  }, [runner, session]);

  /** Snapshot the current offline game and return to the menu so it can be resumed. */
  const saveAndExit = useCallback(() => {
    if (session) { notify('Online games are left with “Step away” — your seat is kept.'); return; }
    if (!runner) { leaveGame(); return; }
    if (runner.game.state.phase === 'finished') { leaveGame(); return; }
    saveGame(runner.game);
    setSaved(listSavedGames());
    notify('Game saved — you can resume it from the menu whenever you like.');
    leaveGame();
  }, [runner, session, leaveGame, notify]);

  /** Rebuild a paused game from its snapshot. */
  const resumeSaved = useCallback((id: string) => {
    const game = loadSavedGame(id);
    if (!game) { notify('That saved game could not be loaded.'); setSaved(listSavedGames()); return; }
    deleteSavedGame(id);
    setSaved(listSavedGames());
    const cfg = game.state.config;
    lastConfig.current = { cfg, names: game.state.players.map((p) => p.name) };
    const sim = cfg.mode === 'offline-sim';
    const r = new GameRunner(game, {
      speed: sim ? 20 : cfg.mode === 'offline-multi' ? 0 : 700,
      tickMs: sim ? 40 : settings.fps === 30 ? 66 : 33,
      stepsPerTick: sim ? 60 : 1,
    });
    r.autoBots = true;
    setSession(null);
    setRunner(r);
    setRoute('game');
    r.start();
    notify(`Resumed the ${cfg.mapPreset} game (round ${game.state.round}).`);
  }, [settings.fps, notify]);

  const replay = useCallback(() => {
    if (!lastConfig.current) { setRoute('play'); return; }
    leaveGame();
    const { cfg, names } = lastConfig.current;
    const cfg2 = { ...cfg, seed: cfg.seed === undefined ? undefined : cfg.seed + 1 };
    startOffline(cfg2, names);
  }, [leaveGame, startOffline]);

  const timerLabel = useMemo(() => {
    if (!runner) return '';
    const t = runner.game.state.config.timer;
    return t === 'none' ? 'no timer' : `timer ${t} (${TIMER_SECONDS[t]}s)`;
  }, [runner]);

  const signedIn = Boolean(profile?.remoteId);
  const onlineAvailable = isSupabaseConfigured;
  const liveGames = sessions.filter((s) => s.status !== 'finished');
  const onlineNames = useMemo(() => {
    const m: Record<string, string> = {};
    for (const s of slot?.seats ?? []) m[s.userId] = s.username;
    return m;
  }, [slot]);

  return (
    <div className="app">
      <header className="topbar">
        <div className="brand" onClick={() => setRoute('menu')} style={{ cursor: 'pointer' }}>
          <span className="brand__mark" />
          <span>GPD<small>Geo-Political Domination</small></span>
        </div>
        <nav className="btn-row">
          <button className="btn btn--sm btn--ghost" onClick={() => setRoute('play')}>Play</button>
          <button className="btn btn--sm btn--ghost" onClick={() => setRoute('online')}>
            Online{liveGames.length ? ` (${liveGames.length})` : ''}
          </button>
          <button className="btn btn--sm btn--ghost" onClick={() => setRoute('leaderboard')}>Leaderboard</button>
          <button className="btn btn--sm btn--ghost" onClick={() => setRoute('rules')}>Rules</button>
        </nav>
        <span className="topbar__spacer" />
        {runner && <span className="pill">{runner.game.state.config.mapPreset} · {timerLabel}</span>}
        <span className={onlineAvailable ? 'pill pill--ok' : 'pill pill--off'}>
          {onlineAvailable ? 'Supabase ready' : 'Offline only'}
        </span>
        {profile ? (
          <div className="userchip">
            <span className="avatar">{profile.username.slice(0, 1).toUpperCase()}</span>
            <span>{profile.username}</span>
            <span className="pill">{signedIn ? 'online' : 'guest'}</span>
            <button className="btn btn--sm btn--ghost" onClick={() => { setProfile(null); setRoute('menu'); }}>Sign out</button>
          </div>
        ) : (
          <button className="btn btn--primary btn--sm" onClick={() => setRoute('auth')}>Sign In / Sign Up</button>
        )}
      </header>

      <div className="app__body">
        {route === 'menu' && (
          <div className="menu">
            <div className="card">
              <h3>Play</h3>
              <p>Offline multiplayer for up to 12 players, singleplayer against 1–12 bots, or a full simulation.</p>
              <button className="btn btn--primary btn--block" onClick={() => setRoute('play')}>Play</button>
            </div>
            <div className="card">
              <h3>Online multiplayer</h3>
              <p>{liveGames.length
                ? `You are in ${liveGames.length} online game${liveGames.length === 1 ? '' : 's'} — rejoin from the list.`
                : 'Host a lobby or join an open game. Everything runs on your account and your username.'}</p>
              <button className="btn btn--block" onClick={() => setRoute('online')}>Open games &amp; lobbies</button>
            </div>
            <div className="card">
              <h3>Resume</h3>
              <p>{saved.length
                ? `${saved.length} saved game${saved.length === 1 ? '' : 's'} waiting to be resumed.`
                : 'Nothing saved yet — exit a game with “Save & exit” to keep it for later.'}</p>
              <button className="btn btn--block" onClick={() => setRoute('resume')}>Resume a game</button>
            </div>
            <div className="card">
              <h3>Settings</h3>
              <p>Frame rate (30/60 FPS), SFX volume and live chat.</p>
              <button className="btn btn--block" onClick={() => setRoute('settings')}>Open settings</button>
            </div>
            <div className="card">
              <h3>Stats</h3>
              <p>Your career totals: games, wins, losses and points.</p>
              <button className="btn btn--block" onClick={() => setRoute('stats')}>View stats</button>
            </div>
            <div className="card">
              <h3>Leaderboard</h3>
              <p>Ranked by global score, and recalculable from any rule set.</p>
              <button className="btn btn--block" onClick={() => setRoute('leaderboard')}>Open leaderboard</button>
            </div>
            <div className="card">
              <h3>Friends</h3>
              <p>Send and accept friend requests.</p>
              <button className="btn btn--block" onClick={() => setRoute('friends')}>Manage friends</button>
            </div>
            <div className="card">
              <h3>Notifications</h3>
              <p>Invitations, friend requests and turn reminders.</p>
              <button className="btn btn--block" onClick={() => setRoute('notifications')}>Open notifications</button>
            </div>
            <div className="card">
              <h3>My Games</h3>
              <p>Local and online game history.</p>
              <button className="btn btn--block" onClick={() => setRoute('mygames')}>Open my games</button>
            </div>
            <div className="card">
              <h3>Rules</h3>
              <p>The complete GPD rulebook.</p>
              <button className="btn btn--block" onClick={() => setRoute('rules')}>Read the rules</button>
            </div>
            <div className="card">
              <h3>Desktop app</h3>
              <p>The offline Python client: same rules, same maps, native window, no account needed.</p>
              <a className="btn btn--block" href={DESKTOP_DOWNLOAD} download="gpd-desktop.zip">
                ⬇ Download for Windows, macOS &amp; Linux
              </a>
              <span className="small muted">{DESKTOP_SIZE} · Python 3.10+ · unzip and run</span>
            </div>
          </div>
        )}

        {route === 'auth' && (
          <Auth
            onSignedIn={(p) => { setProfile(p); setRoute('menu'); notify(`Welcome, ${p.username}.`); }}
            onGuest={() => { setProfile((cur) => cur ?? { username: 'Guest', createdAt: new Date().toISOString() }); setRoute('menu'); }}
          />
        )}

        {route === 'play' && (
          <PlaySetup
            onCancel={() => setRoute('menu')}
            onStart={(cfg, names, lobby) => {
              if (cfg.mode === 'online-solo' || cfg.mode === 'online-teams') hostOnline(cfg, names, lobby);
              else startOffline(cfg, names);
            }}
            onlineSlot={
              <button className="btn btn--sm" onClick={() => setRoute('online')}>Browse open games</button>
            }
          />
        )}

        {route === 'online' && (
          <OnlinePanel
            profile={profile}
            sessions={sessions}
            onJoin={(id, password) => joinLobby(id, password)}
            onRejoin={(s) => resumeOnline(s)}
            onForget={(id) => { deleteOnlineSession(id); setSessions(listOnlineSessions()); }}
            onBack={() => setRoute('play')}
          />
        )}

        {route === 'lobby' && slot && (
          <LobbyPanel
            gameId={slot.gameId}
            userId={slot.userId}
            username={slot.username}
            isHost={slot.isHost}
            seat={slot.seat}
            capacity={slot.capacity}
            status={slot.status}
            config={slot.cfg}
            liveChat={settings.liveChat}
            onSeats={(seats) => {
              const cur = slotRef.current;
              if (!cur) return;
              const next = { ...cur, seats };
              slotRef.current = next;
              setSlot(next);
              if (cur.isHost) cur.channel.sendLobby({ status: cur.status, capacity: cur.capacity, hostId: null, seats });
            }}
            onStart={startLobby}
            onLeave={leaveLobby}
          />
        )}

        {route === 'game' && runner && (
          <GameScreen
            runner={runner}
            settings={settings}
            onExit={leaveGame}
            onSaveExit={saveAndExit}
            canResume={!session}
            onReplay={replay}
            onFinish={finish}
            onStepAway={stepAway}
            onForfeit={forfeitGame}
            online={session
              ? { gameId: session.gameId, userId: session.userId, meSeat: session.meSeat, names: onlineNames }
              : undefined}
          />
        )}

        {route === 'settings' && <SettingsPanel settings={settings} onChange={setSettings} onBack={() => setRoute('menu')} />}
        {route === 'stats' && <StatsPanel games={games} profile={profile} onBack={() => setRoute('menu')} />}
        {route === 'leaderboard' && <LeaderboardPanel games={games} profile={profile} onBack={() => setRoute('menu')} />}
        {route === 'friends' && <FriendsPanel profile={profile} onBack={() => setRoute('menu')} />}
        {route === 'notifications' && <NotificationsPanel profile={profile} onBack={() => setRoute('menu')} />}
        {route === 'mygames' && <MyGamesPanel games={games} profile={profile} onBack={() => setRoute('menu')} />}
        {route === 'resume' && (
          <ResumePanel
            saved={saved}
            onResume={resumeSaved}
            onDelete={(id) => { deleteSavedGame(id); setSaved(listSavedGames()); }}
            onBack={() => setRoute('menu')}
          />
        )}
        {route === 'rules' && <RulesPanel onBack={() => setRoute('menu')} />}
      </div>

      {toast && (
        <div style={{ position: 'fixed', bottom: 18, left: '50%', transform: 'translateX(-50%)', zIndex: 200 }}>
          <div className="notice notice--good">{toast}</div>
        </div>
      )}

      <footer className="footer">
        <span>GPD · Geo-Political Domination</span>
        <span>Web client: TypeScript + React</span>
        <span>Desktop client: Python + Arcade — <a href={DESKTOP_DOWNLOAD} download="gpd-desktop.zip">download</a></span>
        <span>Default settings: {DEFAULT_SETTINGS.fps} FPS · SFX {Math.round(DEFAULT_SETTINGS.sfxVolume * 100)}%</span>
        <span>{games.length} games on this device</span>
      </footer>
    </div>
  );
}
